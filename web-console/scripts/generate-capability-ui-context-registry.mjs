import { readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const GENERATED_HEADER = `// Generated by web-console/scripts/generate-capability-ui-context-registry.mjs.
// This file is a build adapter for component loading only. It must not be used
// as a product route whitelist, installed capability list, or workspace tool registry.
`;

function normalizeCapabilityCode(fileName) {
  return fileName.replace(/\.(ts|tsx|js|jsx)$/, '');
}

export function buildCapabilityUiContextRegistrySource(capabilityCodes) {
  const codes = Array.from(new Set(capabilityCodes))
    .map((code) => String(code || '').trim())
    .filter(Boolean)
    .sort();
  const loaderEntries = codes
    .map((code) => `  ${JSON.stringify(code)}: () => import('./capability-ui-contexts/${code}'),`)
    .join('\n');

  return `${GENERATED_HEADER}
import type { CapabilityComponentsContext } from './capability-ui-context-types';

type CapabilityContextModule = {
  default: CapabilityComponentsContext;
};

type CapabilityContextLoader = () => Promise<CapabilityContextModule>;

const contextLoaders: Record<string, CapabilityContextLoader> = {
${loaderEntries}
};

function capabilityCodeVariants(capabilityCode: string): string[] {
  const variants = new Set<string>();
  const trimmed = capabilityCode.trim();
  if (trimmed) {
    variants.add(trimmed);
    variants.add(trimmed.replace(/-/g, '_'));
    variants.add(trimmed.replace(/_/g, '-'));
  }
  return Array.from(variants);
}

export async function loadRegisteredCapabilityComponentsContext(
  capabilityCode: string,
): Promise<{ capabilityCode: string; context: CapabilityComponentsContext } | null> {
  for (const variant of capabilityCodeVariants(capabilityCode)) {
    const loader = contextLoaders[variant];
    if (!loader) {
      continue;
    }
    const module = await loader();
    return {
      capabilityCode: variant,
      context: module.default,
    };
  }
  return null;
}

export function getRegisteredCapabilityComponentContextCodes(): string[] {
  return Object.keys(contextLoaders);
}
`;
}

async function isDirectory(directoryPath) {
  try {
    return (await stat(directoryPath)).isDirectory();
  } catch {
    return false;
  }
}

export async function filterCapabilityCodesWithSourceDirectories(
  capabilityCodes,
  {
    webConsoleRoot,
  },
) {
  const available = [];
  for (const capabilityCode of capabilityCodes) {
    const sourceDirectory = path.join(
      webConsoleRoot,
      'src/app/capabilities',
      capabilityCode,
    );
    if (await isDirectory(sourceDirectory)) {
      available.push(capabilityCode);
    }
  }
  return available;
}

export async function generateCapabilityUiContextRegistry({
  webConsoleRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'),
} = {}) {
  const contextsDir = path.join(webConsoleRoot, 'src/lib/capability-ui-contexts');
  const registryPath = path.join(webConsoleRoot, 'src/lib/capability-ui-context-registry.ts');
  const entries = await readdir(contextsDir, { withFileTypes: true });
  const contextCapabilityCodes = entries
    .filter((entry) => entry.isFile() && /\.(ts|tsx|js|jsx)$/.test(entry.name))
    .map((entry) => normalizeCapabilityCode(entry.name));
  const capabilityCodes = await filterCapabilityCodesWithSourceDirectories(
    contextCapabilityCodes,
    { webConsoleRoot },
  );

  const source = buildCapabilityUiContextRegistrySource(capabilityCodes);
  await writeFile(registryPath, source, 'utf8');
  return { registryPath, capabilityCodes };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateCapabilityUiContextRegistry();
}
